// Exercise the actual download, frozen snapshots and local failure recovery.
import {createRequire} from 'module';
import {readFileSync, mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH || 'playwright');
const browser=await chromium.launch();
const page=await browser.newPage({acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
let popups=0;page.on('popup',()=>popups++);
const output=new URL('../../../../tmp/pdfs/',import.meta.url);mkdirSync(output,{recursive:true});
await page.goto(new URL('../../v3.html',import.meta.url).href+'#patient/10/overview');
await page.locator('[data-act="reportdlg"]').click();
assert.equal(await page.locator('[data-pickrep]').count(),7);
assert.equal(await page.locator('#report h1').textContent(),'Záznam z MDT');
assert.equal(await page.locator('#report .signature').count(),2);
assert.equal(await page.locator('#report h4').allTextContents().then(x=>x.includes('Schválení')),false);
assert.equal(await page.locator('#report h4').allTextContents().then(x=>x.includes('Anamnéza')),false);
const download=async name=>{
 const event=page.waitForEvent('download');await page.locator('[data-act="download"]').click();const d=await event;
 assert(d.suggestedFilename().endsWith('.pdf'));
 const file=new URL(name,output);await d.saveAs(file.pathname);
 assert(readFileSync(file).subarray(0,5).equals(Buffer.from('%PDF-')));
 return d.suggestedFilename();
};
assert((await download('mdt-default.pdf')).includes('NO-010'));
await page.locator('[data-pickrep="summary"]').uncheck();
assert.equal(await page.locator('#report h4').allTextContents().then(x=>x.includes('NO')),false);
await page.locator('[data-pickrep="summary"]').check();
await page.locator('[data-pickrep="anamnesis"]').check();
assert((await page.locator('#report').textContent()).includes('Alergologická anamnéza: neuvedeno v dostupné dokumentaci'));
await download('mdt-full.pdf');
await page.locator('.modal [data-close]').click();
// Freeze through the real approval path, then mutate live state before downloading it again.
await page.locator('details.mdtcard > summary').click();
await page.locator('#concl').fill('Kontrola MR za 3 měsíce. Žluťoučký kůň, příští vyšetření.');
await page.locator('[data-act="approve"]').click();
await page.locator('[data-act="reportdlg"]').click();
const frozen=await page.locator('#report').innerHTML();
assert.equal(await page.locator('[data-pickrep]:not([disabled])').count(),0);
await page.evaluate(()=>{S.picked.clear();S.edits[EK('brief',S.pid)]={text:'NOVÝ TEXT SE NESMÍ OBJEVIT',by:S.user,when:'now'};S.attByDay[attDay(P(S.pid))]=['NOVÝ ÚČASTNÍK'];});
assert.equal(await page.locator('#report').innerHTML(),frozen);
assert(!(await download('mdt-approved.pdf')).includes('koncept'));
// Generation failure does not log a successful download, and the button becomes usable again.
const n=await page.evaluate(()=>S.access.length);
await page.evaluate(()=>{window.savedPdfLib=window.jspdf;window.jspdf=null;});
await page.locator('[data-act="download"]').click();
await page.locator('#report-error').waitFor({state:'visible'});
assert.equal(await page.locator('[data-act="download"]').isEnabled(),true);
assert.equal(await page.evaluate(()=>S.access.length),n);
await page.evaluate(()=>{window.jspdf=window.savedPdfLib;});
assert.equal(popups,0);
assert.deepEqual(errors,[]);
console.log('PDF downloads, field selection, approval snapshots, Czech text fixture and failure recovery passed.');
await browser.close();
